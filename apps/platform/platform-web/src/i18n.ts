const requestedLanguage = new URLSearchParams(window.location.search).get("lang")
const storedLanguage = localStorage.getItem("genioone.language")
const initialLanguage: ConsoleLanguage =
  requestedLanguage === "zh-TW" || requestedLanguage === "en"
    ? requestedLanguage
    : storedLanguage === "zh-TW" || storedLanguage === "en"
    ? storedLanguage
    : navigator.language.toLowerCase().startsWith("zh")
      ? "zh-TW"
      : "en"

void i18n.use(initReactI18next).init({
  lng: initialLanguage,
  fallbackLng: "en",
  supportedLngs: supportedLanguages,
  keySeparator: false,
  interpolation: { escapeValue: false },
  resources: {
    en: { translation: en },
    "zh-TW": { translation: zhTW },
  },
})

export async function changeConsoleLanguage(language: ConsoleLanguage) {
  localStorage.setItem("genioone.language", language)
  document.documentElement.lang = language
  await i18n.changeLanguage(language)
}

document.documentElement.lang = initialLanguage

